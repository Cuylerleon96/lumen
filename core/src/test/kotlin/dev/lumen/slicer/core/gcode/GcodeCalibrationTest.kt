package dev.lumen.slicer.core.gcode

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Calibration G-code ramps.
 *
 * The pass rewrites a sliced tower so each Z segment runs with its own value. Two things are being
 * checked, and they fail independently:
 *  1. **Placement** — the command must fire at each segment boundary, including when the layer height
 *     does not divide the segment height (0.2 mm layers, 10 mm segments: nothing ever lands *on* the
 *     boundary, so an equality test would silently apply nothing).
 *  2. **Preservation** — every original line must still be there, in order, with its line ending.
 *     A calibration print is disposable; a mangled file is not, because the diagnosis it was supposed
 *     to provide is gone too.
 */
class GcodeCalibrationTest {

    private val gcode = buildString {
        append("; generated by a slicer\n")
        append("G28\n")
        append("G1 Z0.2 F600\n")
        append("G1 X10 Y10 E1\n")
        append("G1 Z10.2 F600\n")
        append("G1 X20 Y20 E2\n")
        append("G1 Z20.2 F600\n")
        append("G1 X30 Y30 E3\n")
    }

    private fun lines(s: String) = s.split("\n").filter { it.isNotEmpty() }

    /** Every line of [original] appears in [rewritten], in order (extra lines allowed). */
    private fun assertPreserved(original: String, rewritten: String) {
        val orig = lines(original)
        val out = lines(rewritten)
        var o = 0
        for (line in out) {
            if (o < orig.size && line == orig[o]) o++
        }
        assertEquals(orig.size, o, "not all original lines survived in order:\n$rewritten")
    }

    @Test
    fun `ramp commands land on the segment boundaries`() {
        val ramp = CalibrationRamp(10f, listOf(230.0, 240.0, 250.0)) { v -> "M104 S${v.toInt()}" }

        val out = GcodeCalibration.apply(gcode, ramp)
        val l = lines(out)

        // segment 0 fires before the first Z move, then one command per boundary crossed
        assertEquals(1, l.count { it == "M104 S230" })
        assertEquals(1, l.count { it == "M104 S240" })
        assertEquals(1, l.count { it == "M104 S250" })

        val i0 = l.indexOf("M104 S230")
        val i1 = l.indexOf("M104 S240")
        val i2 = l.indexOf("M104 S250")
        assertTrue(i0 < l.indexOf("G1 Z0.2 F600"), "segment 0 must apply before the first Z move")
        assertTrue(i1 > l.indexOf("G1 Z0.2 F600") && i1 < l.indexOf("G1 Z10.2 F600"), "240 belongs before Z10.2")
        assertTrue(i2 > l.indexOf("G1 Z10.2 F600") && i2 < l.indexOf("G1 Z20.2 F600"), "250 belongs before Z20.2")
        assertPreserved(gcode, out)
    }

    @Test
    fun `every original line survives in order`() {
        val ramp = GcodeCalibration.temperature(startC = 230, stepC = 5, segments = 3, segmentHeightMm = 10f)

        val out = GcodeCalibration.apply(gcode, ramp)

        assertPreserved(gcode, out)
        assertTrue(out.startsWith("; generated by a slicer\nG28\n"), "the header must be untouched")
    }

    @Test
    fun `a boundary that no layer lands on exactly still fires`() {
        // 0.2 mm layers into 10 mm segments: no Z is ever exactly 10.
        val g = "G1 Z0.2 F600\nG1 Z9.8 F600\nG1 Z10.0 F600\nG1 Z10.2 F600\n"
        val ramp = CalibrationRamp(10f, listOf(1.0, 2.0)) { v -> "M220 S${v.toInt()}" }

        val out = GcodeCalibration.apply(g, ramp)

        val l = lines(out)
        assertEquals(1, l.count { it == "M220 S2" })
        assertTrue(l.indexOf("M220 S2") > l.indexOf("G1 Z9.8 F600"))
    }

    @Test
    fun `one move that clears several boundaries emits each of them`() {
        // A Z hop straight past two boundaries must not skip a segment.
        val g = "G1 Z0.2 F600\nG1 Z35 F600\n"
        val ramp = CalibrationRamp(10f, listOf(1.0, 2.0, 3.0, 4.0)) { v -> "M104 S${v.toInt()}" }

        val out = GcodeCalibration.apply(g, ramp)

        val l = lines(out)
        for (cmd in listOf("M104 S1", "M104 S2", "M104 S3", "M104 S4")) {
            assertEquals(1, l.count { it == cmd }, "$cmd missing from:\n$out")
        }
    }

    @Test
    fun `a temperature ramp waits for the new temperature`() {
        val ramp = GcodeCalibration.temperature(startC = 230, stepC = 5, segments = 2, segmentHeightMm = 10f)

        val out = GcodeCalibration.apply(gcode, ramp)
        val l = lines(out)

        val set = l.indexOf("M104 S230")
        val wait = l.indexOf("M109 S230")
        assertTrue(set >= 0 && wait == set + 1, "M109 must follow its M104:\n$out")
    }

    @Test
    fun `values above the top segment are not emitted`() {
        val ramp = CalibrationRamp(10f, listOf(1.0, 2.0)) { v -> "M220 S${v.toInt()}" }

        val out = GcodeCalibration.apply(gcode, ramp)

        val l = lines(out)
        assertEquals(1, l.count { it == "M220 S1" })
        assertEquals(1, l.count { it == "M220 S2" })
        assertEquals(2, l.count { it.startsWith("M220") }, "a 2-value ramp must not invent a third change")
    }

    @Test
    fun `an empty ramp changes nothing at all`() {
        val ramp = CalibrationRamp(10f, emptyList()) { v -> "M104 S${v.toInt()}" }

        assertEquals(gcode, GcodeCalibration.apply(gcode, ramp))
    }

    @Test
    fun `CRLF line endings are preserved`() {
        val crlf = gcode.replace("\n", "\r\n")
        val ramp = CalibrationRamp(10f, listOf(230.0, 240.0)) { v -> "M104 S${v.toInt()}" }

        val out = GcodeCalibration.apply(crlf, ramp)

        assertTrue(out.contains("M104 S230\r\n"), "inserted lines must use the file's own ending")
        assertTrue(out.contains("G1 Z0.2 F600\r\n"), "original endings must survive")
        assertEquals(0, out.replace("\r\n", "").count { it == '\r' }, "no stray CR")
    }

    @Test
    fun `valueAt maps a Z height to its segment`() {
        val ramp = CalibrationRamp(10f, listOf(230.0, 240.0, 250.0)) { v -> "M104 S${v.toInt()}" }

        assertEquals(230.0, ramp.valueAt(0f))
        assertEquals(230.0, ramp.valueAt(9.99f))
        assertEquals(240.0, ramp.valueAt(10f))
        assertEquals(250.0, ramp.valueAt(25f))
        assertEquals(null, ramp.valueAt(30f))
    }
}
